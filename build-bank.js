#!/usr/bin/env node
// Regenerates data/bank.js from the source question bank JSON.
// Usage: node build-bank.js path/to/safety-quiz-2026.json
// No dependencies. The JSON is copied verbatim into a global so the page
// can load it with a plain <script src> tag under file://.
"use strict";
const fs = require("fs");
const path = require("path");

const src = process.argv[2];
if (!src) {
  console.error("Usage: node build-bank.js path/to/safety-quiz-2026.json");
  process.exit(1);
}
const bank = JSON.parse(fs.readFileSync(src, "utf8"));
if (!Array.isArray(bank.chapters) || !Array.isArray(bank.questions)) {
  console.error("Not a question bank: expected chapters[] and questions[].");
  process.exit(1);
}
// U+2028 and U+2029 are escaped so the output is valid in every JS engine.
const LS = String.fromCharCode(0x2028), PS = String.fromCharCode(0x2029);
const json = JSON.stringify(bank).split(LS).join("\\u2028").split(PS).join("\\u2029");
const out = path.join(__dirname, "data", "bank.js");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, "// Generated by build-bank.js. Do not edit by hand.\nwindow.SAFETY_BANK = " + json + ";\n");
console.log("Wrote " + out);
console.log("Edition " + bank.edition + ": " + bank.chapters.length + " chapters, " + bank.questions.length + " questions");
